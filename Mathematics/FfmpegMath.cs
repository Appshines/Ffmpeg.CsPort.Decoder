				: (int)value;
		}

		public static int ClipSignedPowerOfTwo(int value, int power)
		{
			if ((unchecked((uint)value + (1U << power)) & ~((2U << power) - 1)) != 0)
			{
				return (value >> 31) ^ ((1 << power) - 1);
			}

			return value;
		}

