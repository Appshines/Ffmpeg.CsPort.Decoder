		public static long SaturatingAdd64(long first, long second)
		{
			var sum = unchecked((long)(unchecked((ulong)first) + unchecked((ulong)second)));
			if ((first ^ second | ~sum ^ second) >= 0)
			{
				return long.MaxValue ^ (second >> 63);
			}

			return sum;
		}

		public static long SaturatingSubtract64(long first, long second)
		{
			if (second <= 0 && first >= long.MaxValue + second)
			{
				return long.MaxValue;
			}
			if (second >= 0 && first <= long.MinValue + second)
			{
				return long.MinValue;
			}

			return first - second;
		}

