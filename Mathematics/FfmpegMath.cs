		public static int Log2(uint value)
		{
			var result = 0;
			if ((value & 0xffff0000U) != 0)
			{
				value >>= 16;
				result += 16;
			}
			if ((value & 0xff00U) != 0)
			{
				value >>= 8;
				result += 8;
			}

			return result + Log2Byte((byte)value);
		}

		public static int CountTrailingZeros(ulong value)
		{
			if (value == 0)
			{
				return 64;
			}

			var count = 0;
			while ((value & 1) == 0)
			{
				value >>= 1;
				count++;
			}

			return count;
		}

		public static int CountTrailingZeros(uint value)
		{
			if (value == 0)
			{
				return 32;
			}

			var count = 0;
			while ((value & 1) == 0)
			{
				value >>= 1;
				count++;
			}

			return count;
		}

		public static int CountLeadingZeros(uint value)
		{
			var count = 32;
			while (value != 0)
			{
				value >>= 1;
				count--;
			}

			return count;
		}

		public static int CeilLog2(int value)
		{
			return Log2(unchecked((uint)(value - 1) << 1));
		}

		public static int PopCount(ulong value)
		{
			return PopCount((uint)value) + PopCount((uint)(value >> 32));
		}

		public static int PopCount(uint value)
		{
			value -= (value >> 1) & 0x55555555U;
			value = (value & 0x33333333U) + ((value >> 2) & 0x33333333U);
			value = (value + (value >> 4)) & 0x0f0f0f0fU;
			value += value >> 8;
			return (int)((value + (value >> 16)) & 0x3fU);
		}

		public static int Parity(uint value)
		{
			return PopCount(value) & 1;
		}

		public static long Gcd(long first, long second)
		{
			if (first == 0)
			{
				return second;
			}
			if (second == 0)
			{
				return first;
			}

			var firstZeros = CountTrailingZeros(unchecked((ulong)first));
			var secondZeros = CountTrailingZeros(unchecked((ulong)second));
			var commonZeros = Math.Min(firstZeros, secondZeros);
			var firstValue = Absolute(first >> firstZeros);
			var secondValue = Absolute(second >> secondZeros);
			while (firstValue != secondValue)
			{
				if (firstValue > secondValue)
				{
					var temporary = secondValue;
					secondValue = firstValue;
					firstValue = temporary;
				}
				secondValue -= firstValue;
				secondValue >>= CountTrailingZeros((ulong)secondValue);
			}

			return unchecked((long)((ulong)firstValue << commonZeros));
		}

		/// <summary>
		/// Preserves FFmpeg's split 64-bit multiply/divide path and every rounding branch of av_rescale_rnd.
		/// </summary>
		public static long RescaleRounding(long value, long multiplier, long divisor, AvRounding rounding)
		{
			long roundingOffset = 0;
			var baseRounding = rounding & ~AvRounding.PassMinMax;
			if (divisor <= 0 || multiplier < 0 || (uint)baseRounding > 5 || baseRounding == (AvRounding)4)
			{
				return long.MinValue;
			}

			if ((rounding & AvRounding.PassMinMax) != 0)
			{
				if (value == long.MinValue || value == long.MaxValue)
				{
					return value;
				}
				rounding -= AvRounding.PassMinMax;
			}

			if (value < 0)
			{
				var positiveValue = unchecked(-Math.Max(value, -long.MaxValue));
				var inverseRounding = rounding ^ (AvRounding)(((int)rounding >> 1) & 1);
				return unchecked((long)(0UL - (ulong)RescaleRounding(positiveValue, multiplier, divisor, inverseRounding)));
			}

			if (rounding == AvRounding.NearInfinity)
			{
				roundingOffset = divisor / 2;
			} else if (((int)rounding & 1) != 0)
			{
				roundingOffset = divisor - 1;
			}

			if (multiplier <= int.MaxValue && divisor <= int.MaxValue)
			{
				if (value <= int.MaxValue)
				{
					return (value * multiplier + roundingOffset) / divisor;
				}

				var dividedValue = value / divisor;
				var remainder = (value % divisor * multiplier + roundingOffset) / divisor;
				if (dividedValue >= int.MaxValue && multiplier != 0 && dividedValue > (long.MaxValue - remainder) / multiplier)
				{
					return long.MinValue;
				}

				return dividedValue * multiplier + remainder;
			}

			var valueLow = (ulong)value & 0xffffffffUL;
			var valueHigh = (ulong)value >> 32;
			var multiplierLow = (ulong)multiplier & 0xffffffffUL;
			var multiplierHigh = (ulong)multiplier >> 32;
			var quotient = unchecked(valueLow * multiplierHigh + valueHigh * multiplierLow);
			var shiftedProduct = unchecked(quotient << 32);
			valueLow = unchecked(valueLow * multiplierLow + shiftedProduct);
			valueHigh = unchecked(valueHigh * multiplierHigh + (quotient >> 32) + (valueLow < shiftedProduct ? 1UL : 0UL));
			var unsignedOffset = (ulong)roundingOffset;
			valueLow = unchecked(valueLow + unsignedOffset);
			valueHigh = unchecked(valueHigh + (valueLow < unsignedOffset ? 1UL : 0UL));

			for (var index = 63; index >= 0; index--)
			{
				valueHigh = unchecked(valueHigh + valueHigh + ((valueLow >> index) & 1));
				quotient = unchecked(quotient + quotient);
				if ((ulong)divisor <= valueHigh)
				{
					valueHigh -= (ulong)divisor;
					quotient++;
				}
			}
			if (quotient > long.MaxValue)
			{
				return long.MinValue;
			}

			return (long)quotient;
		}

		public static long Rescale(long value, long multiplier, long divisor)
		{
			return RescaleRounding(value, multiplier, divisor, AvRounding.NearInfinity);
		}

		public static long RescaleRational(long value, AvRational source, AvRational destination, AvRounding rounding = AvRounding.NearInfinity)
		{
			var multiplier = source.Numerator * (long)destination.Denominator;
			var divisor = destination.Numerator * (long)source.Denominator;
			return RescaleRounding(value, multiplier, divisor, rounding);
		}

		/// <summary>
		/// Reduces or continued-fraction-approximates a rational within FFmpeg's signed integer bound.
		/// </summary>
		public static bool Reduce(out int destinationNumerator, out int destinationDenominator, long numerator, long denominator, long maximum)
		{
			var first = new AvRational(0, 1);
			var second = new AvRational(1, 0);
			var negative = (numerator < 0) ^ (denominator < 0);
			var divisor = Gcd(Absolute(numerator), Absolute(denominator));
			if (divisor != 0)
			{
				numerator = Absolute(numerator) / divisor;
				denominator = Absolute(denominator) / divisor;
			}
			if (numerator <= maximum && denominator <= maximum)
			{
				second = new AvRational((int)numerator, (int)denominator);
				denominator = 0;
			}

			while (denominator != 0)
			{
				var factor = (ulong)(numerator / denominator);
				var nextDenominator = numerator - denominator * (long)factor;
				var nextNumerator = (long)factor * second.Numerator + first.Numerator;
				var nextRationalDenominator = (long)factor * second.Denominator + first.Denominator;
				if (nextNumerator > maximum || nextRationalDenominator > maximum)
				{
					if (second.Numerator != 0)
					{
						factor = (ulong)((maximum - first.Numerator) / second.Numerator);
					}
					if (second.Denominator != 0)
					{
						factor = Math.Min(factor, (ulong)((maximum - first.Denominator) / second.Denominator));
					}
					if (denominator * (2 * (long)factor * second.Denominator + first.Denominator) > numerator * second.Denominator)
					{
						second = new AvRational(
							(int)((long)factor * second.Numerator + first.Numerator),
							(int)((long)factor * second.Denominator + first.Denominator));
					}
					break;
				}

				first = second;
				second = new AvRational((int)nextNumerator, (int)nextRationalDenominator);
				numerator = denominator;
				denominator = nextDenominator;
			}

			destinationNumerator = negative ? -second.Numerator : second.Numerator;
			destinationDenominator = second.Denominator;
			return denominator == 0;
		}

		public static AvRational Multiply(AvRational first, AvRational second)
		{
			Reduce(out first.Numerator, out first.Denominator,
				first.Numerator * (long)second.Numerator,
				first.Denominator * (long)second.Denominator,
				int.MaxValue);
			return first;
		}

		public static AvRational Divide(AvRational first, AvRational second)
		{
			return Multiply(first, new AvRational(second.Denominator, second.Numerator));
		}

		public static AvRational Add(AvRational first, AvRational second)
		{
			Reduce(out first.Numerator, out first.Denominator,
				first.Numerator * (long)second.Denominator + second.Numerator * (long)first.Denominator,
				first.Denominator * (long)second.Denominator,
				int.MaxValue);
			return first;
		}

		public static AvRational Subtract(AvRational first, AvRational second)
		{
			return Add(first, new AvRational(-second.Numerator, second.Denominator));
		}

		public static AvRational FromDouble(double value, int maximum)
		{
			if (double.IsNaN(value))
			{
				return new AvRational(0, 0);
			}
			if (Math.Abs(value) > int.MaxValue + 3L)
			{
				return new AvRational(value < 0 ? -1 : 1, 0);
			}

			var exponent = value == 0 ? 0 : Math.ILogB(value) + 1;
			exponent = Math.Max(exponent - 1, 0);
			var denominator = 1L << (62 - exponent);
			Reduce(out var numerator, out var reducedDenominator,
				(long)Math.Floor(value * denominator + 0.5), denominator, maximum);
			return new AvRational(numerator, reducedDenominator);
		}

		public static int Nearer(AvRational value, AvRational first, AvRational second)
		{
			var numerator = first.Numerator * (long)second.Denominator + second.Numerator * (long)first.Denominator;
			var denominator = 2 * (long)first.Denominator * second.Denominator;
			var upper = RescaleRounding(numerator, value.Denominator, denominator, AvRounding.Up);
			var lower = RescaleRounding(numerator, value.Denominator, denominator, AvRounding.Down);
			return ((upper > value.Numerator ? 1 : 0) - (lower < value.Numerator ? 1 : 0)) * second.Compare(first);
		}

		public static int FindNearestIndex(AvRational value, AvRational[] values)
		{
			var nearestIndex = 0;
			for (var index = 0; values[index].Denominator != 0; index++)
			{
				if (Nearer(value, values[index], values[nearestIndex]) > 0)
				{
					nearestIndex = index;
				}
			}

			return nearestIndex;
		}

		public static uint RationalToIntFloat(AvRational value)
		{
			if (value.Denominator < 0)
			{
				value.Denominator *= -1;
				value.Numerator *= -1;
			}
			var sign = 0;
			if (value.Numerator < 0)
			{
				value.Numerator *= -1;
				sign = 1;
			}
			if (value.Numerator == 0 && value.Denominator == 0)
			{
				return 0xffc00000U;
			}
			if (value.Numerator == 0)
			{
				return 0;
			}
			if (value.Denominator == 0)
			{
				return 0x7f800000U | ((uint)value.Numerator & 0x80000000U);
			}

			var shift = 23 + Log2((uint)value.Denominator) - Log2((uint)value.Numerator);
			long scaled = shift >= 0
				? Rescale(value.Numerator, 1L << shift, value.Denominator)
				: Rescale(value.Numerator, 1, (long)value.Denominator << -shift);
			shift -= scaled >= 1 << 24 ? 1 : 0;
			shift += scaled < 1 << 23 ? 1 : 0;
			scaled = shift >= 0
				? Rescale(value.Numerator, 1L << shift, value.Denominator)
				: Rescale(value.Numerator, 1, (long)value.Denominator << -shift);
			return (uint)(sign << 31 | (150 - shift) << 23 | (int)(scaled - (1 << 23)));
		}

		public static AvRational Gcd(AvRational first, AvRational second, int maximumDenominator, AvRational defaultValue)
		{
			var divisor = Gcd(first.Denominator, second.Denominator);
			var leastCommonMultiple = first.Denominator / divisor * second.Denominator;
			return leastCommonMultiple < maximumDenominator
				? new AvRational((int)Gcd(first.Numerator, second.Numerator), (int)leastCommonMultiple)
				: defaultValue;
		}

		public static int CompareTimestamps(long firstTimestamp, AvRational firstTimeBase, long secondTimestamp, AvRational secondTimeBase)
		{
			var firstScale = firstTimeBase.Numerator * (long)secondTimeBase.Denominator;
			var secondScale = secondTimeBase.Numerator * (long)firstTimeBase.Denominator;
			if ((AbsoluteUnsigned(firstTimestamp) | (ulong)firstScale | AbsoluteUnsigned(secondTimestamp) | (ulong)secondScale) <= int.MaxValue)
			{
				var firstValue = firstTimestamp * firstScale;
				var secondValue = secondTimestamp * secondScale;
				return (firstValue > secondValue ? 1 : 0) - (firstValue < secondValue ? 1 : 0);
			}
			if (RescaleRounding(firstTimestamp, firstScale, secondScale, AvRounding.Down) < secondTimestamp)
			{
				return -1;
			}
			if (RescaleRounding(secondTimestamp, secondScale, firstScale, AvRounding.Down) < firstTimestamp)
			{
				return 1;
			}

			return 0;
		}

		public static long CompareModulo(ulong first, ulong second, ulong modulo)
		{
			var difference = unchecked((long)((first - second) & (modulo - 1)));
			if (difference > (long)(modulo >> 1))
			{
				difference -= (long)modulo;
			}

			return difference;
		}

		public static long RescaleDelta(AvRational inputTimeBase, long inputTimestamp, AvRational sampleTimeBase,
			int duration, ref long last, AvRational outputTimeBase)
		{
			if (last == long.MinValue || duration == 0 ||
				inputTimeBase.Numerator * (long)outputTimeBase.Denominator <= outputTimeBase.Numerator * (long)inputTimeBase.Denominator)
			{
				last = RescaleRational(inputTimestamp, inputTimeBase, sampleTimeBase) + duration;
				return RescaleRational(inputTimestamp, inputTimeBase, outputTimeBase);
			}

			var lower = RescaleRational(2 * inputTimestamp - 1, inputTimeBase, sampleTimeBase, AvRounding.Down) >> 1;
			var upper = (RescaleRational(2 * inputTimestamp + 1, inputTimeBase, sampleTimeBase, AvRounding.Up) + 1) >> 1;
			if (last < 2 * lower - upper || last > 2 * upper - lower)
			{
				last = RescaleRational(inputTimestamp, inputTimeBase, sampleTimeBase) + duration;
				return RescaleRational(inputTimestamp, inputTimeBase, outputTimeBase);
			}

			var current = Clip(last, lower, upper);
			last = current + duration;
			return RescaleRational(current, sampleTimeBase, outputTimeBase);
		}

		public static long AddStable(AvRational timestampTimeBase, long timestamp, AvRational incrementTimeBase, long increment)
		{
			if (increment != 1)
			{
				incrementTimeBase = Multiply(incrementTimeBase, new AvRational((int)increment, 1));
			}

			var multiplier = incrementTimeBase.Numerator * (long)timestampTimeBase.Denominator;
			var divisor = incrementTimeBase.Denominator * (long)timestampTimeBase.Numerator;
			if (multiplier % divisor == 0 && timestamp <= long.MaxValue - multiplier / divisor)
			{
				return timestamp + multiplier / divisor;
			}
			if (multiplier < divisor)
			{
				return timestamp;
			}

			var old = RescaleRational(timestamp, timestampTimeBase, incrementTimeBase);
			var oldTimestamp = RescaleRational(old, incrementTimeBase, timestampTimeBase);
			if (old == long.MaxValue || old == long.MinValue || oldTimestamp == long.MinValue)
			{
				return timestamp;
			}

			return SaturatingAdd64(RescaleRational(old + 1, incrementTimeBase, timestampTimeBase), timestamp - oldTimestamp);
		}

		public static double BesselI0(double value)
		{
			if (value == 0)
			{
				return 1.0;
			}
			value = Math.Abs(value);
			if (value <= 15)
			{
				var squared = value * value;
				return EvaluatePolynomial(s_BesselP1, squared) / EvaluatePolynomial(s_BesselQ1, squared);
			}

			var inverse = 1 / value - 1.0 / 15;
			var ratio = EvaluatePolynomial(s_BesselP2, inverse) / EvaluatePolynomial(s_BesselQ2, inverse);
			var factor = Math.Exp(value) / Math.Sqrt(value);
			return factor * ratio;
		}

		/// <summary>Preserves the scalar exp2f range reduction, polynomial schedule, and final float rounding used by the reference build.</summary>
		public static float Exp2Float(float value)
		{
			if (value < -126.0f || value >= 128.0f || !float.IsFinite(value)) return float.Exp2(value);
			const double rounding = 211106232532992.0;
			var input = (double)value;
			var roundedWithMagic = input + rounding;
			var rounded = roundedWithMagic - rounding;
			var residual = input - rounded;
			var cubicCoefficient = residual * 0.05550361559341535;
			var higherPolynomial = cubicCoefficient + 0.2402284522445722;
			var squared = residual * residual;
			var linear = residual * 0.6931471806916203;
			var higherTerms = higherPolynomial * squared;
			var lowerTerms = linear + 1.0;
			var polynomial = higherTerms + lowerTerms;
			var roundedBits = unchecked((ulong)BitConverter.DoubleToInt64Bits(roundedWithMagic));
			var scaleBits = unchecked((roundedBits << 47) + s_Exp2FloatScale[roundedBits & 31]);
			var scale = BitConverter.Int64BitsToDouble(unchecked((long)scaleBits));
			return (float)(polynomial * scale);
		}

		private static int Log2Byte(byte value)
		{
			var result = 0;
			while (value > 1)
			{
				value >>= 1;
				result++;
			}

			return result;
		}

		private static double EvaluatePolynomial(double[] coefficients, double value)
		{
			var sum = coefficients[coefficients.Length - 1];
			for (var index = coefficients.Length - 2; index >= 0; index--)
			{
				sum *= value;
				sum += coefficients[index];
			}

			return sum;
		}
	}

	/// <summary>
	/// Matches the numeric values and bit flags of FFmpeg's AVRounding enumeration.
	/// </summary>
	[Flags]
	internal enum AvRounding
	{
		Zero = 0,
		Infinity = 1,
		Down = 2,
		Up = 3,
		NearInfinity = 5,
		PassMinMax = 8192
	}
