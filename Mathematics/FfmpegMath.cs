		public static int Absolute(int value)
		{
			return value >= 0 ? value : unchecked(-value);
		}

		public static long Absolute(long value)
		{
			return value >= 0 ? value : unchecked(-value);
		}

		public static uint AbsoluteUnsigned(int value)
		{
			return value <= 0 ? unchecked(0U - (uint)value) : (uint)value;
		}

		public static ulong AbsoluteUnsigned(long value)
		{
			return value <= 0 ? unchecked(0UL - (ulong)value) : (ulong)value;
		}

		public static int RoundedRightShift(int value, int bitCount)
		{
			var rounding = (1 << bitCount) >> 1;
			return value > 0 ? value + rounding >> bitCount : value + rounding - 1 >> bitCount;
		}

		public static int RoundedDivide(int value, int divisor)
		{
			return value >= 0 ? (value + (divisor >> 1)) / divisor : (value - (divisor >> 1)) / divisor;
		}

		public static int CeilRightShift(int value, int bitCount)
		{
			return (value + (1 << bitCount) - 1) >> bitCount;
		}

		public static int UnsignedDivide(int value, int divisor)
		{
			return (value > 0 ? value : value - divisor + 1) / divisor;
		}

		public static int UnsignedModulo(int value, int divisor)
		{
			return value - divisor * UnsignedDivide(value, divisor);
		}

